use std::collections::HashMap;
use std::sync::OnceLock;

/// `packet_lengths.txt`: every packet rAthena knows at this PACKETVER, generated by `tools/packet-lengths`.
static LENGTHS: OnceLock<HashMap<u16, i32>> = OnceLock::new();

/// A packet's length by ID: fixed, or -1 where the packet carries its own length at offset 2.
pub fn packet_length(id: u16) -> Option<i32> {
    LENGTHS
        .get_or_init(|| {
            include_str!("packet_lengths.txt")
                .lines()
                .chain(include_str!("packet_lengths_more.txt").lines())
                .filter_map(|line| {
                    let (id, length) = line.strip_prefix("0x")?.split_once(' ')?;
                    Some((u16::from_str_radix(id, 16).ok()?, length.trim().parse().ok()?))
                })
                .collect()
        })
        .get(&id)
        .copied()
}

#[derive(Debug, PartialEq)]
pub enum Frame {
    /// Bytes outside any packet: the account ID the char server sends before its first packet.
    Raw(Vec<u8>),
    /// One whole packet, its ID included.
    Packet(u16, Vec<u8>),
}

#[derive(Debug, PartialEq)]
pub enum FrameError {
    /// An ID the length table does not have. The stream cannot be followed past it.
    UnknownPacket(u16),
    /// A variable-length packet that claims to be shorter than its own header.
    BadLength(u16, u16),
}

impl std::fmt::Display for FrameError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnknownPacket(id) => write!(formatter, "unknown packet {id:#06x}"),
            Self::BadLength(id, length) => write!(formatter, "packet {id:#06x} claims a length of {length}"),
        }
    }
}

/// Cuts the server's byte stream into packets. Bytes arrive in pieces of any size; a packet is given out once it is
/// whole.
#[derive(Default)]
pub struct Framer {
    buffer: Vec<u8>,
    raw: usize,
}

impl Framer {
    pub fn new() -> Self {
        Self::default()
    }

    /// The next `count` bytes are not a packet and come out as `Frame::Raw`.
    pub fn expect_raw(&mut self, count: usize) {
        self.raw = count;
    }

    pub fn push(&mut self, bytes: &[u8]) {
        self.buffer.extend_from_slice(bytes);
    }

    /// The packet the bytes held so far begin, if they do not make a whole one: its ID, and how many bytes are
    /// held. Many bytes held for long tell of a length that is not the server's.
    pub fn waiting(&self) -> Option<(u16, usize)> {
        (self.buffer.len() >= 2).then(|| (u16::from_le_bytes([self.buffer[0], self.buffer[1]]), self.buffer.len()))
    }

    /// The next whole frame, or `None` until more bytes arrive.
    pub fn next(&mut self) -> Result<Option<Frame>, FrameError> {
        if self.raw > 0 {
            if self.buffer.len() < self.raw {
                return Ok(None);
            }
            let raw = self.buffer.drain(..self.raw).collect();
            self.raw = 0;
            return Ok(Some(Frame::Raw(raw)));
        }
        if self.buffer.len() < 2 {
            return Ok(None);
        }
        let id = u16::from_le_bytes([self.buffer[0], self.buffer[1]]);
        let length = match packet_length(id).ok_or(FrameError::UnknownPacket(id))? {
            -1 => {
                if self.buffer.len() < 4 {
                    return Ok(None);
                }
                let length = u16::from_le_bytes([self.buffer[2], self.buffer[3]]);
                if length < 4 {
                    return Err(FrameError::BadLength(id, length));
                }
                usize::from(length)
            }
            length => length as usize,
        };
        if self.buffer.len() < length {
            return Ok(None);
        }
        Ok(Some(Frame::Packet(id, self.buffer.drain(..length).collect())))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_length_table_has_the_packets_of_the_way_in() {
        for (id, length) in [(0x0064, 55), (0x0ac4, -1), (0x083e, 26), (0x0065, 17), (0x006b, -1), (0x0a39, 36), (0x0b6f, 177), (0x0ac5, 156), (0x0436, 23), (0x02eb, 13)]
        {
            assert_eq!(packet_length(id), Some(length), "{id:#06x}");
        }
        assert_eq!(packet_length(0xffff), None);
    }

    #[test]
    fn cuts_fixed_and_variable_packets_out_of_one_buffer() {
        let mut framer = Framer::new();
        // HC_REFUSE_ENTER (3 bytes), a variable packet of 6, then the first byte of another packet.
        framer.push(&[0x6c, 0x00, 7, 0x6b, 0x00, 6, 0, 0xaa, 0xbb, 0x81]);
        assert_eq!(framer.next(), Ok(Some(Frame::Packet(0x006c, vec![0x6c, 0x00, 7]))));
        assert_eq!(framer.next(), Ok(Some(Frame::Packet(0x006b, vec![0x6b, 0x00, 6, 0, 0xaa, 0xbb]))));
        assert_eq!(framer.next(), Ok(None));
        framer.push(&[0x00, 8]);
        assert_eq!(framer.next(), Ok(Some(Frame::Packet(0x0081, vec![0x81, 0x00, 8]))));
        assert_eq!(framer.next(), Ok(None));
    }

    #[test]
    fn waits_for_a_packet_that_arrives_byte_by_byte() {
        let packet = [0x6b, 0x00, 7, 0, 1, 2, 3];
        let mut framer = Framer::new();
        for (index, byte) in packet.iter().enumerate() {
            assert_eq!(framer.next(), Ok(None), "after {index} bytes");
            framer.push(&[*byte]);
        }
        assert_eq!(framer.next(), Ok(Some(Frame::Packet(0x006b, packet.to_vec()))));
    }

    /// The char server sends the bare account ID first, and it may come together with the first packet.
    #[test]
    fn gives_raw_bytes_before_the_first_packet() {
        let mut framer = Framer::new();
        framer.expect_raw(4);
        framer.push(&[0x80, 0x84]);
        assert_eq!(framer.next(), Ok(None));
        framer.push(&[0x1e, 0x00, 0x6c, 0x00, 0]);
        assert_eq!(framer.next(), Ok(Some(Frame::Raw(vec![0x80, 0x84, 0x1e, 0x00]))));
        assert_eq!(framer.next(), Ok(Some(Frame::Packet(0x006c, vec![0x6c, 0x00, 0]))));
    }

    #[test]
    fn stops_at_what_it_cannot_follow() {
        let mut framer = Framer::new();
        framer.push(&[0xff, 0xff, 0, 0]);
        assert_eq!(framer.next(), Err(FrameError::UnknownPacket(0xffff)));

        let mut framer = Framer::new();
        framer.push(&[0x6b, 0x00, 3, 0]);
        assert_eq!(framer.next(), Err(FrameError::BadLength(0x006b, 3)));
    }
}
